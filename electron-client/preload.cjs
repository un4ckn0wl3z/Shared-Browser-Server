const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('sharedBrowser', {
  bootstrap: () => ipcRenderer.invoke('browser:bootstrap'),
  unlock: (code) => ipcRenderer.invoke('browser:unlock', code),
  downloads: () => ipcRenderer.invoke('browser:downloads'),
  downloadAction: (id, action) => ipcRenderer.invoke('browser:download-action', id, action),
  clearDownloads: () => ipcRenderer.invoke('browser:clear-downloads'),
  onDownloads: (callback) => ipcRenderer.on('browser:downloads', (_, value) => callback(value)),
  onDownloadStarted: (callback) => ipcRenderer.on('browser:download-started', (_, value) => callback(value)),
  onLock: (callback) => ipcRenderer.on('browser:lock', (_, value) => callback(value)),
  navigate: (url) => ipcRenderer.invoke('browser:navigate', url),
  back: () => ipcRenderer.invoke('browser:back'),
  forward: () => ipcRenderer.invoke('browser:forward'),
  reload: () => ipcRenderer.invoke('browser:reload'),
  stop: () => ipcRenderer.invoke('browser:stop'),
  newTab: (url) => ipcRenderer.invoke('browser:new-tab', url),
  selectTab: (id) => ipcRenderer.invoke('browser:select-tab', id),
  closeTab: (id) => ipcRenderer.invoke('browser:close-tab', id),
  syncNow: () => ipcRenderer.invoke('browser:sync-now'),
  privacyCheck: () => ipcRenderer.invoke('browser:privacy-check'),
  checkIp: () => ipcRenderer.invoke('browser:check-ip'),
  setSettingsOpen: (open) => ipcRenderer.invoke('browser:settings-open', Boolean(open)),
  saveSettings: (settings) => ipcRenderer.invoke('browser:save-settings', settings),
  checkForUpdates: () => ipcRenderer.invoke('browser:check-updates'),
  installUpdate: () => ipcRenderer.invoke('browser:install-update'),
  showBookmarks: (position) => ipcRenderer.invoke('browser:show-bookmarks', position),
  showAccounts: (position) => ipcRenderer.invoke('browser:show-accounts', position),
  addAccount: (name) => ipcRenderer.invoke('browser:add-account', name),
  shareSite: (input) => ipcRenderer.invoke('browser:share-site', input),
  switchAccount: (id) => ipcRenderer.invoke('browser:switch-account', id),
  onAddAccount: (callback) => ipcRenderer.on('browser:add-account', (_, value) => callback(value)),
  reopenTab: () => ipcRenderer.invoke('browser:reopen-tab'),
  find: (text, options) => ipcRenderer.invoke('browser:find', text, options),
  stopFind: () => ipcRenderer.invoke('browser:stop-find'),
  dismissAnnouncement: (id) => ipcRenderer.invoke('browser:dismiss-announcement', id),
  openAnnouncementLink: (id) => ipcRenderer.invoke('browser:open-announcement-link', id),
  setChromeHeight: (height) => ipcRenderer.invoke('browser:chrome-height', height),
  onState: (callback) => ipcRenderer.on('browser:state', (_, value) => callback(value)),
  onTabs: (callback) => ipcRenderer.on('browser:tabs', (_, value) => callback(value)),
  onStatus: (callback) => ipcRenderer.on('browser:status', (_, value) => callback(value)),
  onShowSettings: (callback) => ipcRenderer.on('browser:show-settings', () => callback()),
  onFocusAddress: (callback) => ipcRenderer.on('browser:focus-address', () => callback()),
  onUpdate: (callback) => ipcRenderer.on('browser:update', (_, value) => callback(value)),
  onBookmarks: (callback) => ipcRenderer.on('browser:bookmarks', (_, value) => callback(value)),
  onAnnouncements: (callback) => ipcRenderer.on('browser:announcements', (_, value) => callback(value)),
  onConfig: (callback) => ipcRenderer.on('browser:config', (_, value) => callback(value)),
  onShowFind: (callback) => ipcRenderer.on('browser:show-find', (_, value) => callback(value)),
  onFindResult: (callback) => ipcRenderer.on('browser:find-result', (_, value) => callback(value))
});
